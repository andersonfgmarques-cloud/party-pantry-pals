-- Projeto 555: controle de contribuições por família e preços de referência.
-- A migração é aditiva: não altera nem remove reservas, participantes ou produtos existentes.
create table if not exists public.party_families (
  id integer generated by default as identity primary key,
  name text not null unique,
  target_amount numeric(10,2) not null default 250 check (target_amount >= 0),
  created_at timestamptz not null default now()
);
insert into public.party_families (id, name, target_amount) values
  (1, 'Família 1', 250), (2, 'Família 2', 250), (3, 'Família 3', 250),
  (4, 'Família 4', 250), (5, 'Família 5', 250), (6, 'Família 6', 250)
on conflict (id) do nothing;
select setval(pg_get_serial_sequence('public.party_families','id'),
  greatest((select coalesce(max(id),1) from public.party_families), 6), true);
alter table public.party_participants add column if not exists family_id integer references public.party_families(id) on delete set null;
alter table public.party_products
  add column if not exists reference_price numeric(10,2) check (reference_price is null or reference_price >= 0),
  add column if not exists reference_source text,
  add column if not exists reference_updated_at timestamptz;
alter table public.party_families enable row level security;
