create extension if not exists pgcrypto;

create table public.party_categories (
  id integer generated by default as identity primary key,
  name text not null unique,
  icon text not null default 'package'
);

create table public.party_event (
  id integer generated by default as identity primary key,
  name text not null default 'Festa na Chácara',
  party_date date,
  guests integer check (guests is null or guests > 0)
);

create table public.party_participants (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 2 and 60),
  token_hash text not null unique,
  created_at timestamptz default now()
);

create table public.party_products (
  id uuid primary key default gen_random_uuid(),
  category_id integer not null references public.party_categories(id),
  name text not null check (char_length(trim(name)) between 1 and 100),
  quantity numeric(12,2) check (quantity is null or quantity > 0),
  unit text not null default 'un.',
  note text,
  received boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.party_reservations (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.party_products(id) on delete cascade,
  participant_id uuid not null references public.party_participants(id) on delete cascade,
  participant_name text not null,
  quantity numeric(12,2) not null check (quantity > 0),
  source text not null check (source in ('home','buy')),
  created_at timestamptz default now()
);

